// lotus-bsdf-tables: generates the directional albedo tables of
// docs/design/LAYERED_BSDF.md section 5.6 from the lobes' own
// single-scattering functions. bsdf-probe.slang compiles the real
// lobes.slang, albedo.slang and composed.slang to C++; for every node of
// every table this builds a closure of the one uncompensated lobe, at the
// node's outgoing direction, and integrates its sample weight over the
// sampler's two random numbers by composite Gauss-Legendre quadrature:
//
//   E(wo) = integral over [0, 1)^2 of f * cos(theta_i) / p (wi(u)) du,
//
// which is the lobe's albedo by a change of variables. The axes and nodes
// come from albedo.slang through the probe.
//
// Usage: lotus-bsdf-tables <output .inc> [tolerance]
//        lotus-bsdf-tables --check <.inc> [tolerance]
// --check reports each table's largest error against a fresh quadrature at
// its nodes and at its cells' centres.

#include "bsdf-tables.hpp"

#include <algorithm>
#include <cstdlib>
#include <atomic>
#include <cstdio>
#include <string>
#include <thread>
#include <vector>

namespace {

std::FILE* OpenFile(const char* path, const char* mode) {
#ifdef _MSC_VER
  std::FILE* file = nullptr;
  return fopen_s(&file, path, mode) == 0 ? file : nullptr;
#else
  return std::fopen(path, mode);
#endif
}

// The floats of a generated .inc, comments skipped.
std::vector<float> ReadInc(const char* path) {
  std::vector<float> values;
  std::FILE* in = OpenFile(path, "r");
  if (!in) return values;
  char line[65536];
  while (std::fgets(line, sizeof(line), in)) {
    if (line[0] == '/') continue;
    for (char* at = line; *at;) {
      char* end = nullptr;
      const float v = std::strtof(at, &end);
      if (end == at) {
        ++at;
        continue;
      }
      values.push_back(v);
      at = end;
    }
  }
  std::fclose(in);
  return values;
}

int Check(const char* path, double tolerance) {
  const std::vector<float> data = ReadInc(path);
  const lotus::AlbedoLayout layout = lotus::ReadAlbedoLayout();
  if (int(data.size()) != layout.size) {
    std::fprintf(stderr, "lotus-bsdf-tables: %s holds %zu floats, the layout %d\n",
        path, data.size(), layout.size);
    return 1;
  }
  for (bool at_nodes : {true, false}) {
    const auto errors = lotus::CheckTables(data.data(), at_nodes, tolerance);
    for (int part = 0; part < lotus::kAlbedoParts; ++part) {
      std::printf("%s %-20s max error %.3g over %lld points at %s\n",
          at_nodes ? "nodes  " : "centres", lotus::kAlbedoPartNames[part],
          errors[part].error, errors[part].points, errors[part].where.c_str());
    }
  }
  return 0;
}

}  // namespace

int main(int argc, char** argv) {
  if (argc >= 3 && std::string(argv[1]) == "--check") {
    return Check(argv[2], argc == 4 ? std::stod(argv[3]) : lotus::kTableTolerance);
  }
  if (argc < 2 || argc > 3) {
    std::fprintf(stderr, "usage: lotus-bsdf-tables <output .inc> [tolerance]\n");
    return 2;
  }
  const double tolerance = argc == 3 ? std::stod(argv[2]) : lotus::kTableTolerance;
  const lotus::AlbedoLayout layout = lotus::ReadAlbedoLayout();
  std::vector<float> data(std::size_t(layout.size), 0.0f);

  struct Node {
    int table, cosine, alpha, layer;
  };
  std::vector<Node> nodes;
  for (int table = 0; table < lotus::kAlbedoTables; ++table) {
    const auto& shape = layout.shape[table];
    for (int layer = 0; layer < shape[2]; ++layer) {
      for (int alpha = 0; alpha < shape[1]; ++alpha) {
        for (int cosine = 0; cosine < shape[0]; ++cosine) {
          nodes.push_back({table, cosine, alpha, layer});
        }
      }
    }
  }
  std::atomic<std::size_t> next{0};
  std::vector<std::thread> pool;
  const unsigned threads = std::max(1u, std::thread::hardware_concurrency());
  for (unsigned t = 0; t < threads; ++t) {
    pool.emplace_back([&] {
      for (std::size_t i; (i = next.fetch_add(1)) < nodes.size();) {
        const Node& n = nodes[i];
        const lotus::AlbedoNode node =
            lotus::ReadAlbedoNode(n.table, n.cosine, n.alpha, n.layer);
        const auto& shape = layout.shape[n.table];
        const std::size_t index = std::size_t(layout.offset[n.table]) +
            (std::size_t(n.layer) * shape[1] + n.alpha) * shape[0] + n.cosine;
        data[index] = float(lotus::IntegrateAlbedo(n.table, node, tolerance));
      }
    });
  }
  for (std::thread& thread : pool) thread.join();

  std::FILE* out = OpenFile(argv[1], "w");
  if (!out) {
    std::fprintf(stderr, "lotus-bsdf-tables: cannot write %s\n", argv[1]);
    return 1;
  }
  std::fprintf(out,
      "// SPDX-License-Identifier: Apache-2.0\n"
      "// Generated by lotus-bsdf-tables (validation/bsdf-tables.cpp) from the\n"
      "// lobes of backend/vulkan/shaders/bsdf/lobes.slang, in the layout of\n"
      "// albedo.slang: %d floats, quadrature tolerance %g. Do not edit;\n"
      "// regenerate it in the change that moves a lobe or an axis.\n",
      layout.size, tolerance);
  for (int table = 0; table < lotus::kAlbedoTables; ++table) {
    const auto& shape = layout.shape[table];
    std::fprintf(out, "// table %d: offset %d, %d cosines x %d alphas x %d layers\n",
        table, layout.offset[table], shape[0], shape[1], shape[2]);
    const int begin = layout.offset[table];
    const int end = begin + shape[0] * shape[1] * shape[2];
    for (int i = begin; i < end; i += shape[0]) {
      for (int c = 0; c < shape[0]; ++c) {
        std::fprintf(out, "%.6g,", data[std::size_t(i + c)]);
      }
      std::fprintf(out, "\n");
    }
  }
  std::fclose(out);
  std::printf("lotus-bsdf-tables: wrote %d floats to %s\n", layout.size, argv[1]);
  return 0;
}
